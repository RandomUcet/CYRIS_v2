/**
 * Focused translation consistency check.
 * Compares all keys in canonical English dictionary against cs, de, pl.
 * Logs a diagnostic table if any keys are missing in non-English dictionaries.
 */
export function checkTranslationConsistency(): { ok: boolean; missing: Record<SupportedLocale, string[]> } {
  const enKeys = Object.keys(translations.en);
  const locales: SupportedLocale[] = ['cs', 'de', 'pl'];
  const missing: Record<SupportedLocale, string[]> = {
    en: [],
    cs: [],
    de: [],
    pl: [],
  };

  let allClean = true;
  for (const loc of locales) {
    const locDict = translations[loc] || {};
    for (const key of enKeys) {
      if (!locDict[key]) {
        missing[loc].push(key);
        allClean = false;
      }
    }
  }

  if (!allClean && typeof process !== 'undefined' && process.env?.NODE_ENV !== 'production') {
    console.warn('[CYRIS i18n] Translation catalog consistency check found missing keys:');
    for (const loc of locales) {
      if (missing[loc].length > 0) {
        console.warn(`  Locale '${loc}' missing ${missing[loc].length} keys:`, missing[loc].slice(0, 10));
      }
    }
  }

  return { ok: allClean, missing };
}

// Run check once in development
if (typeof globalThis !== 'undefined' && 'window' in globalThis && typeof process !== 'undefined' && process.env?.NODE_ENV !== 'production') {
  checkTranslationConsistency();
}

/**
 * Translates a key for a given locale, with strict fallback to English.
 * User-authored operational text is NEVER silently translated.
 */
export function translate(
  locale: SupportedLocale,
  key: string,
  params?: Record<string, string | number>
): string {
  const dict = translations[locale] || translations.en;
  let text = dict[key] || translations.en[key] || key;

  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }

  return text;
}

/**
 * Formats a timestamp into an operational time string based on active locale + timezone.
 */
export function formatOperationalTime(
  dateInput: Date | string | number | null | undefined,
  timeZone: string = 'UTC',
  locale: SupportedLocale = 'en',
  options?: Intl.DateTimeFormatOptions
): string {
  if (!dateInput) return '—';
  const date = typeof dateInput === 'string' || typeof dateInput === 'number' ? new Date(dateInput) : dateInput;
  if (isNaN(date.getTime())) return '—';

  const defaultOptions: Intl.DateTimeFormatOptions = {
    timeZone,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
    ...options,
  };

  try {
    const intlLocale = locale === 'cs' ? 'cs-CZ' : locale === 'de' ? 'de-DE' : locale === 'pl' ? 'pl-PL' : 'en-GB';
    return new Intl.DateTimeFormat(intlLocale, defaultOptions).format(date);
  } catch {
    return date.toISOString();
  }
}

/**
 * Formats a date into a compact operational date string based on active locale + timezone.
 */
export function formatOperationalDate(
  dateInput: Date | string | number | null | undefined,
  timeZone: string = 'UTC',
  locale: SupportedLocale = 'en',
  options?: Intl.DateTimeFormatOptions
): string {
  if (!dateInput) return '—';
  const date = typeof dateInput === 'string' || typeof dateInput === 'number' ? new Date(dateInput) : dateInput;
  if (isNaN(date.getTime())) return '—';

  const defaultOptions: Intl.DateTimeFormatOptions = {
    timeZone,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    ...options,
  };

  try {
    const intlLocale = locale === 'cs' ? 'cs-CZ' : locale === 'de' ? 'de-DE' : locale === 'pl' ? 'pl-PL' : 'en-GB';
    return new Intl.DateTimeFormat(intlLocale, defaultOptions).format(date);
  } catch {
    return date.toISOString().slice(0, 10);
  }
}
